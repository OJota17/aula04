// Calcule a soma de todos os números de 1 a 100 utilizando um laço de repetição (USANDO O WHILE E FOR)

var num = 1
var result = 0

while (num <= 100){
    result = result + num
    num++
    console.log(result)
}


//For

for(var i = 1; i <= 100; i++){
    result = result + i
    console.log(result)
}